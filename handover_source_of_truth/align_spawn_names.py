"""Align spawn-map option labels with sim node ids and link defaults.

The sim is the fixed part: option labels are renamed to the node they set.
Option ids stay the same. Writes a rename table to RENAMES.md next to this file.

Run: .venv/bin/python handover_source_of_truth/align_spawn_names.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "update.json"
OUT_MD = Path(__file__).resolve().parent / "RENAMES.md"

d = json.loads(SRC.read_text())
sp = d["spawn"]
E, O, P = sp["elements"], sp["options"], sp["points"]
nodes = {n["id"]: n for n in d["nodes"]}
sp_no = {pid: p["id"] for pid, p in P.items()}


def where(o):
    el = E[o["elemId"]]
    return f"SP {sp_no.get(el['spawnPointId'], '?')} · {el['name']}"


def node_effect(o):
    """The node + value an option sets, read from its explicit effects."""
    effs = o.get("effects") or []
    return effs[0] if effs else None


log = []  # (where, old, new, change)


def rename(o, new, change=""):
    old = o["label"]
    if old != new or change:
        log.append((where(o), old, new, change))
    o["label"] = new


def set_effects(o, effs):
    o["effects"] = [{"node_id": n, "op": "set", "value": v} for n, v in effs]


# 1 · options linked through node_id or a single explicit effect -> node id
#     (setting + value where several options in one slot share a node)
shared = {"bus_stop_design", "ns_outer_parking_spawn_4"}
for o in O.values():
    eff = node_effect(o)
    if eff and eff["node_id"] in shared:
        rename(o, f"{eff['node_id']}_{int(eff['value'])}")
    elif o.get("node_id"):
        rename(o, o["node_id"])

# 2 · cosmetic options linked to an existing node (+1 each, read as node_id)
links = {
    "bench": "urban_furniture",
    "parklet_greenery_and_seating": "urban_furniture",
    "parklett_greenery_seating": "urban_furniture",
    "fountain": "blue_infrastructure",
    "tree_lined_avenue_with_pockets": "spawn_2_canopy_streets",
    "sport_terrain": "sport_facility",
    "sport_terrain_ spanning_4_and_5": "sport_facility",
}
for o in O.values():
    lab = o["label"]
    if lab in links and not o.get("node_id"):
        o["node_id"] = links[lab]
        rename(o, links[lab], f"linked: +1 {links[lab]}")

# 3 · defaults: keep their name, link them by setting the starting value
for o in O.values():
    el = E[o["elemId"]]
    lab, en = o["label"], el["name"]
    if lab == "parking" and en == "lane_1/8":
        set_effects(o, [("sidewalk_extension_spawn_2", 0), ("bike_lanes_spawn_2", 0)])
        log.append((where(o), lab, lab, "linked: sidewalk_extension_spawn_2 = 0, bike_lanes_spawn_2 = 0"))
    elif lab == "nothing" and en == "facade":
        set_effects(o, [("green_facades", 0)])
        log.append((where(o), lab, lab, "linked: green_facades = 0"))
    elif lab == "unused groundfloor":
        set_effects(o, [("cafe", 0)])
        log.append((where(o), lab, lab, "linked: cafe = 0"))
    elif lab == "nothing" and en.replace(" ", "") == "busstop":
        set_effects(o, [("bus_stop_design", 0)])
        log.append((where(o), lab, lab, "linked: bus_stop_design = 0"))

# 4 · starting states must name the (renamed) starting option
starts = {
    "lane_2/7": "car_lanes_spawn_2",   # was empty; the sim starts 2/7 as a car lane
    "lane_3/6": "car_lanes_spawn_2",   # was "car lane"
    "lane_a/f": "ns_outer_parking_spawn_4_1",  # was "parking"
}
start_log = []
for el in E.values():
    if el["name"] in starts and el.get("startingState") != starts[el["name"]]:
        start_log.append((f"SP {sp_no[el['spawnPointId']]} · {el['name']}", el.get("startingState") or "(empty)", starts[el["name"]]))
        el["startingState"] = starts[el["name"]]

# checks: every node_id / effect points at a real active node
bad = []
for o in O.values():
    for n in [o.get("node_id")] + [e["node_id"] for e in o.get("effects") or []]:
        if n and (n not in nodes or nodes[n]["type"] != "active"):
            bad.append((o["id"], n))
assert not bad, bad

SRC.write_text(json.dumps(d, indent=2, ensure_ascii=False) + "\n")

lines = ["# Spawn-map renames (sim names are fixed)", "",
         "Option ids are unchanged; only labels changed. Generated by `align_spawn_names.py`.", "",
         "| Where | Old label | New label | Link change |", "|---|---|---|---|"]
lines += [f"| {w} | `{a}` | `{b}` | {c} |" for w, a, b, c in log]
lines += ["", "## Starting states", "", "| Element | Old | New |", "|---|---|---|"]
lines += [f"| {w} | `{a}` | `{b}` |" for w, a, b in start_log]
OUT_MD.write_text("\n".join(lines) + "\n")
print(f"{len(log)} option changes, {len(start_log)} starting states")
